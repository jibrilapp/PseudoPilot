#!/usr/bin/env node
/**
 * Walks repo docs markdown tree and emits lib/docs/corpus.generated.ts.
 * Run via predev / prebuild / pretest so new pages appear automatically.
 */
/* global console */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const webRoot = path.resolve(__dirname, '..');
const docsRoot = path.resolve(webRoot, '../../docs');
const outFile = path.resolve(webRoot, 'lib/docs/corpus.generated.ts');

function walkMarkdown(dir, base = dir) {
  /** @type {{ path: string; content: string }[]} */
  const entries = [];
  if (!fs.existsSync(dir)) {
    throw new Error(`docs root not found: ${dir}`);
  }
  for (const name of fs.readdirSync(dir, { withFileTypes: true })) {
    if (name.name.startsWith('.')) continue;
    const full = path.join(dir, name.name);
    if (name.isDirectory()) {
      entries.push(...walkMarkdown(full, base));
      continue;
    }
    if (!name.isFile() || !name.name.endsWith('.md')) continue;
    const rel = path.relative(base, full).split(path.sep).join('/');
    entries.push({
      path: rel,
      content: fs.readFileSync(full, 'utf8'),
    });
  }
  return entries;
}

const entries = walkMarkdown(docsRoot).sort((a, b) =>
  a.path.localeCompare(b.path),
);

const banner = `/**
 * AUTO-GENERATED by scripts/generate-docs-corpus.mjs — do not edit.
 * Source of truth: repo docs markdown files.
 */
`;

const body = `${banner}export type DocCorpusEntry = {
  path: string;
  content: string;
};

export const DOC_CORPUS: readonly DocCorpusEntry[] = ${JSON.stringify(entries, null, 2)} as const;
`;

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, body, 'utf8');
console.log(
  `Generated ${entries.length} docs → ${path.relative(webRoot, outFile)}`,
);
